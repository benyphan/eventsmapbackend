import re

# Словарь запрещённого/подозрительного контента.
# Совпадение хотя бы одного слова => пост уходит на модерацию,
# а не публикуется сразу. Окончательное решение принимает модератор.
BANNED_WORDS = [
    # нецензурная лексика (мат)
    "хуй", "хуё", "хуе", "хуя", "хуи", "нахуй", "похуй", "оху", "аху", "хуйня",
    "хуета", "пизд", "пиздец", "пизда", "пизду", "бля", "блядь", "бляд", "ебал",
    "ебать", "ебет", "ебут", "ебу", "еби", "ебло", "уёб", "уеб", "заеб", "наеб",
    "выеб", "объеб", "мудак", "мудил", "сука", "суки", "сук ", "залупа", "залуп",
    "манда", "шлюха", "шлюх", "гандон", "пидор", "пидр", "пидар", "хуесос",
    "срать", "срет", "ссал", "ссать", "дерьмо", "говно", "жопа", "жопу",
    "член", "давалка", "проститут", "тварь",
    # нацистская и экстремистская символика / идеология
    "свастик", "нацист", "наци ", "нация идей", "гитлер", "зиг хайль",
    "зигхайль", "хайль", "фашист", "фашизм", "гестапо", "вермахт", "белый орден",
    "фюрер", "концлагер", "зигзаг победы",
    # флаги и политические символы (спорные изображения)
    "флаг украины", "жовто-блакитн", "украинский флаг", "тризуб",
    # порнография и взрослый контент
    "порно", "порнография", "гей-порно", "порнух", "эротика", "секс-видео",
    "интим-услуги", "интим фото", "нюдсы",
]

# Приведение к нижнему регистру и нормализация похожих букв (а -> а, 0 -> о)
_TRANS = str.maketrans({
    "ё": "е",
    "0": "о",
    "1": "л",
    "4": "а",
    "3": "е",
    "6": "б",
    "@": "а",
    "$": "с",
})


def normalize(text: str) -> str:
    return text.lower().translate(_TRANS)


def contains_banned(text: str) -> bool:
    """True, если текст содержит запрещённые/подозрительные слова."""
    if not text:
        return False
    norm = normalize(text)
    for word in BANNED_WORDS:
        if word in norm:
            return True
    return False
